"""Run against the local server. Explicitly creates labeled fixture resources."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

root=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1050},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.goto('http://127.0.0.1:8765'); page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading',name='实验工作台',exact=True)).to_be_visible()
    page.get_by_role('button',name='数据集版本',exact=False).click()
    page.get_by_role('button',name='发布数据集版本',exact=True).click()
    expect(page.get_by_text('3 个样本',exact=True).last).to_be_visible()
    page.get_by_role('button',name='被测服务',exact=False).click()
    page.get_by_label('名称',exact=True).fill('浏览器验收：正确目标')
    page.get_by_role('button',name='注册版本',exact=True).click()
    expect(page.get_by_text('浏览器验收：正确目标',exact=True).last).to_be_visible()
    page.get_by_role('button',name='实验工作台',exact=False).click()
    datasets=page.request.get('http://127.0.0.1:8765/api/v1/resources/dataset').json()
    targets=page.request.get('http://127.0.0.1:8765/api/v1/resources/target').json()
    page.get_by_label('数据集版本',exact=True).select_option(next(d['id'] for d in datasets if d['name']=='经营数据验收集 v1'))
    page.get_by_label('被测服务版本',exact=True).select_option(next(t['id'] for t in targets if t['name']=='浏览器验收：正确目标'))
    page.get_by_label('实验名称',exact=True).fill('浏览器验收：基线')
    page.get_by_role('button',name='创建并执行',exact=True).click()
    expect(page.get_by_text('通过 3 / 3',exact=True)).to_be_visible(timeout=15000)
    page.get_by_role('button',name='被测服务',exact=False).click()
    page.get_by_label('名称',exact=True).fill('浏览器验收：退化目标')
    page.get_by_label('测试行为',exact=True).select_option('regression')
    page.get_by_role('button',name='注册版本',exact=True).click()
    expect(page.get_by_text('浏览器验收：退化目标',exact=True).last).to_be_visible()
    page.get_by_role('button',name='实验工作台',exact=False).click()
    page.get_by_label('实验名称',exact=True).fill('浏览器验收：候选退化')
    targets=page.request.get('http://127.0.0.1:8765/api/v1/resources/target').json()
    page.get_by_label('被测服务版本',exact=True).select_option(next(t['id'] for t in targets if t['name']=='浏览器验收：退化目标'))
    page.get_by_role('button',name='创建并执行',exact=True).click()
    expect(page.get_by_text('通过 2 / 3',exact=True)).to_be_visible(timeout=15000)
    page.screenshot(path=str(root/'docs'/'workbench.png'),full_page=True)
    page.get_by_role('button',name='版本对比',exact=False).click()
    runs=page.request.get('http://127.0.0.1:8765/api/v1/runs').json()
    a=next(r['id'] for r in runs if r['name']=='浏览器验收：基线')
    b=next(r['id'] for r in runs if r['name']=='浏览器验收：候选退化')
    page.get_by_label('基线',exact=True).select_option(a)
    page.get_by_label('候选',exact=True).select_option(b)
    page.get_by_role('button',name='比较实验',exact=True).click()
    expect(page.get_by_role('heading',name='通过率变化 -33.3 个百分点')).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path=str(root/'docs'/'mobile.png'),full_page=True)
    assert not errors,errors
    browser.close()
    print('Browser acceptance PASS: dataset, target, baseline, regression, comparison, mobile; no JS errors.')
